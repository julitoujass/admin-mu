"""Port of the payment terminal: what the application needs from a card/QR device.

The application (`PagoService`) depends only on this module. Each provider (the
in-memory `FakeTerminal`, Clover in stage C) is an adapter that implements
`PaymentTerminal`; nothing provider-specific may leak through these types.

Contract shared by every adapter:

- Amounts are integer cents.
- `charge` blocks until the customer finishes (up to ~135 s) and never retries by
  itself. When the adapter cannot tell whether the customer was charged (timeout,
  5xx, network error) it returns `ChargeOutcome.UNKNOWN` or raises
  `TerminalUnavailable`; the caller then reconciles with `find_by_external_id`.
- `TerminalBusy` and `TerminalBadRequest` mean the charge was NOT started.
- `find_by_external_id` returns `None` only when the terminal positively answers
  that it has no payment with that id; if it cannot answer it raises
  `TerminalUnavailable` (or returns an `UNKNOWN` result).
- `raw` is the provider response for troubleshooting. Adapters must not put full
  card numbers, track data or cardholder names in it, and must never log card data.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Literal, Protocol, runtime_checkable

PaymentMethod = Literal["Tarjeta", "QR"]


class ChargeOutcome(str, Enum):
    APPROVED = "APPROVED"
    DECLINED = "DECLINED"
    CANCELLED = "CANCELLED"  # cancelled on the device or from the POS
    UNKNOWN = "UNKNOWN"  # the terminal could not say whether the customer was charged


class RefundOutcome(str, Enum):
    DONE = "DONE"
    FAILED = "FAILED"
    UNKNOWN = "UNKNOWN"


class TerminalStatus(str, Enum):
    IDLE = "IDLE"
    BUSY = "BUSY"
    WAITING_FOR_CUSTOMER = "WAITING_FOR_CUSTOMER"
    UNKNOWN = "UNKNOWN"


@dataclass(frozen=True)
class ChargeRequest:
    external_id: str  # generated by us, at most 32 characters, unique per charge
    amount_cents: int
    metodo: PaymentMethod
    description: str = ""


@dataclass(frozen=True)
class ChargeResult:
    outcome: ChargeOutcome
    provider_payment_id: str | None = None
    card_brand: str | None = None
    last4: str | None = None
    auth_code: str | None = None
    installments: int | None = None
    entry_type: str | None = None
    raw: dict[str, Any] = field(default_factory=dict)
    error: str | None = None


@dataclass(frozen=True)
class RefundResult:
    outcome: RefundOutcome
    refund_id: str | None = None
    raw: dict[str, Any] = field(default_factory=dict)
    error: str | None = None


class TerminalError(Exception):
    """Base class of the errors a terminal adapter may raise."""


class TerminalBusy(TerminalError):
    """The device is in the middle of another operation; the request was not started."""


class TerminalUnavailable(TerminalError):
    """The device or its cloud could not be reached, or did not answer in time."""


class TerminalBadRequest(TerminalError):
    """The terminal rejected the request as invalid; it was not started."""


@runtime_checkable
class PaymentTerminal(Protocol):
    def ping(self) -> bool:
        """Whether the device is connected. Must answer quickly."""

    def status(self) -> TerminalStatus: ...

    def charge(self, req: ChargeRequest) -> ChargeResult:
        """Charge the customer. Blocking, up to ~135 s."""

    def find_by_external_id(self, external_id: str) -> ChargeResult | None:
        """Result of a previous charge, or None when the terminal has no such payment."""

    def cancel_current(self) -> None:
        """Ask the device to cancel what is on screen. The charge itself reports the final result."""

    def refund(self, payment_id: str, amount_cents: int | None) -> RefundResult:
        """Refund a payment by its provider id; `amount_cents=None` refunds it in full."""

    def show_welcome(self) -> None:
        """Return the device to its idle screen (sent after every transaction)."""
